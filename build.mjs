import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';

const root = new URL('./', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const dictionaries = {};
for (const locale of ['en', 'zh']) {
  const resource = JSON.parse(await readFile(new URL(`locale/${locale}.json`, root), 'utf8'));
  if (!resource.meta?.title || !resource.meta?.description) throw new Error(`Missing ${locale} inventory metadata`);
  dictionaries[locale] = Object.fromEntries(Object.entries(resource).filter(([key]) => key !== 'meta'));
  if (Object.values(dictionaries[locale]).some(value => typeof value !== 'string')) throw new Error(`Non-flat ${locale} dictionary`);
}
if (Object.keys(dictionaries.en).sort().join() !== Object.keys(dictionaries.zh).sort().join()) throw new Error('Locale keys differ');
const source = await readFile(new URL('src/client.js', root), 'utf8');
if (!source.includes('export function createClientPlugin(')) throw new Error('Missing Client factory');
const body = source.replace(/^export (?=function (?:createClientPlugin|shouldShowWorktreePickers)\()/gm, '');
const output = `// Generated by build.mjs from src/client.js; ${manifest.name}@${manifest.version}\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(manifest.name)},\n  factory(require) {\n    const React = require('react');\n${body}\n    return createClientPlugin(React, ${JSON.stringify(dictionaries)});\n  },\n});\n`;
new Script(output, { filename: 'client.js' });
// Read an existing artifact before replacing it; builds never modify Host/profile state.
const target = new URL('client.js', root);
await readFile(target, 'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; });
await writeFile(target, output);
console.log(`Built ${fileURLToPath(target)} (${Buffer.byteLength(output)} bytes)`);
