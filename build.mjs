import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';

const root = new URL('./', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const dictionaries = {};
for (const locale of ['en', 'zh']) {
  const resource = JSON.parse(await readFile(new URL(`locale/${locale}.json`, root), 'utf8'));
  if (!resource.meta?.title || !resource.meta?.description) throw new Error(`Missing ${locale} inventory metadata`);
  dictionaries[locale] = Object.fromEntries(Object.entries(resource).filter(([key]) => key !== 'meta'));
  if (Object.values(dictionaries[locale]).some(value => typeof value !== 'string')) throw new Error(`Non-flat ${locale} dictionary`);
}
if (Object.keys(dictionaries.en).sort().join() !== Object.keys(dictionaries.zh).sort().join()) throw new Error('Locale keys differ');
const source = await readFile(new URL('src/client.js', root), 'utf8');
if (!source.includes('export function createClientPlugin(')) throw new Error('Missing Client factory');
const changesSource = await readFile(new URL('src/changes-client.js', root), 'utf8');
if (!changesSource.includes('export function createChangesUI(')) throw new Error('Missing changes UI factory');
const progressSource = await readFile(new URL('src/progress-client.js', root), 'utf8');
const recoverySource = await readFile(new URL('src/recovery-client.js', root), 'utf8');
const browserSource = await readFile(new URL('src/browser-client.js', root), 'utf8');
const previewSource = await readFile(new URL('src/file-preview.js', root), 'utf8');
const importLine = "import { createChangesUI, parseUnifiedPatch } from './changes-client.js';\nimport { createPreparationUI } from './progress-client.js';\nimport { createRecoveryUI } from './recovery-client.js';\nimport { createBrowserUI } from './browser-client.js';\nimport { createFilePreview } from './file-preview.js';\n";
if (!source.startsWith(importLine)) throw new Error('Unexpected Client module import');
const body = `${previewSource.replace(/^export (?=function )/gm, '')}\n${browserSource.replace("import { filePreviewType } from './file-preview.js';\n", '').replace(/^export (?=function )/gm, '')}\n${recoverySource.replace(/^export (?=function )/gm, '')}\n${progressSource.replace(/^export (?=function )/gm, '')}\n${changesSource.replace(/^export (?=function )/gm, '')}\n${source.slice(importLine.length).replace(/^export (?=function (?:createClientPlugin|shouldShowWorktreePickers)\()/gm, '')}`;
if (/^(?:import|export)\s/m.test(body)) throw new Error('Unsupported browser module import/export');
const output = `// Generated by build.mjs from src/client.js and src/changes-client.js; ${manifest.name}@${manifest.version}\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(manifest.name)},\n  factory(require) {\n    const React = require('react');\n${body}\n    return createClientPlugin(React, ${JSON.stringify(dictionaries)});\n  },\n});\n`;
new Script(output, { filename: 'client.js' });
// Read an existing artifact before replacing it; builds never modify Host/profile state.
const target = new URL('client.js', root);
await readFile(target, 'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; });
await writeFile(target, output);
console.log(`Built ${fileURLToPath(target)} (${Buffer.byteLength(output)} bytes)`);
